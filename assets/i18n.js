export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function translate(locale, key, params = {}) {
  const resolvedLocale = normalizeLocale(locale);
  const template = TRANSLATIONS[resolvedLocale][key] ?? TRANSLATIONS[DEFAULT_LOCALE][key] ?? key;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function readLocale(storage = globalThis.localStorage) {
  try {
    return normalizeLocale(storage?.getItem(LOCALE_STORAGE_KEY));
  } catch {
    return DEFAULT_LOCALE;
  }
}

export function writeLocale(locale, storage = globalThis.localStorage) {
  const resolvedLocale = normalizeLocale(locale);
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, resolvedLocale);
  } catch {
    return resolvedLocale;
  }
  return resolvedLocale;
}

export function currentLocale() {
  return readLocale();
}

export function t(key, params = {}) {
  return translate(currentLocale(), key, params);
}

export function formatNumber(value, options = {}, locale = currentLocale()) {
  return new Intl.NumberFormat(normalizeLocale(locale), options).format(value);
}

export function applyLocale(root = globalThis.document) {
  if (!root) return currentLocale();
  const locale = currentLocale();
  root.documentElement.lang = locale;
  root.documentElement.dataset.currentLocale = locale;
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(locale, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(locale, element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(locale, element.dataset.i18nAriaLabel));
  });
  const titleKey = root.querySelector('meta[name="i18n-title"]')?.content;
  if (titleKey) root.title = translate(locale, titleKey);
  const description = root.querySelector('meta[name="description"]');
  const descriptionKey = description?.dataset.i18nContent;
  if (descriptionKey) description.content = translate(locale, descriptionKey);
  root.querySelectorAll("[data-locale]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.locale === locale);
    button.setAttribute("aria-pressed", String(button.dataset.locale === locale));
  });
  return locale;
}

export function setupLanguageSwitcher(root = globalThis.document, location = globalThis.location) {
  if (!root) return;
  root.querySelectorAll("[data-locale]").forEach((button) => {
    button.addEventListener("click", () => {
      writeLocale(button.dataset.locale);
      location?.reload();
    });
  });
}
